"""Collect eval results into evals/RESULTS.md.  Run: uv run python -m evals.report"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).parent
R = HERE / "results"


def load(name: str) -> dict | None:
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def pct(x: dict) -> str:
    return f"{x['ok']}/{x['n']} ({x['rate'] * 100:.0f}%)" if x and x.get("n") else "n/a"


def main() -> None:
    out = ["# Evaluation results", "", "Generated by `uv run python -m evals.report` from `evals/results/*.json`. Re-run any eval to refresh.", ""]

    g = load("grading.json")
    if g:
        m = g["metrics"]
        out += [
            "## 1. Notebook grading benchmark", "",
            f"{len(g['raw'])} phone-photo-style notebook pages rendered by Muse Image from written specs (`evals/grading_specs.py`), "
            f"{m['problems_scored']} scored problems covering Class 2-6 addition, subtraction (incl. borrow across zero), multiplication, "
            "long division, fractions, decimals and 4-digit arithmetic, with 16 planted misconceptions. Labels are what is actually drawn on each "
            "page (checked by eye); right/wrong for each label is computed by sympy.", "",
            "| Metric | Apni Gati pipeline | Model-only baseline (one Muse Spark call) |", "|---|---|---|",
            f"| Right/wrong accuracy | {pct(m['pipeline']['status_accuracy'])} | {pct(m['baseline_model_only']['status_accuracy'])} |",
            f"| Correct work marked wrong | {pct(m['pipeline']['false_wrong (correct work marked wrong)'])} | {pct(m['baseline_model_only']['false_wrong (correct work marked wrong)'])} |",
            f"| Mistakes missed | {pct(m['pipeline']['false_correct (mistake missed)'])} | {pct(m['baseline_model_only']['false_correct (mistake missed)'])} |",
            f"| Sent to teacher review | {pct(m['pipeline']['needs_review'])} | — |",
            f"| Problems found on page | {pct(m['problems_found'])} | — |",
            f"| Final answer transcribed exactly | {pct(m['answer_read_exact'])} | — |",
            f"| Misconception diagnosed exactly | {pct(m['misconception_exact'])} | — (baseline gives no diagnosis) |",
            f"| Misconception at right concept/root | {pct(m['misconception_same_concept_or_root'])} | — |",
            "",
            f"Cost ${g['cost_usd_total']:.2f} for all pages; median {g['seconds_per_page_median']} s per page (problems on a page run in parallel).", "",
            "**Honest reading:** on clean pages Muse Spark alone already judges right/wrong very well (the baseline scored 40/40; the "
            "pipeline's single miss was sent to teacher review because the zoomed re-read could not confirm the answer, not marked wrong). "
            "What the pipeline adds is "
            "that every mark is *proved* by sympy rather than asserted, the first wrong working step is located and circled on the photo, the "
            "misconception is diagnosed against the NCERT concept graph, unreadable or incomplete problems go to the teacher instead of being "
            "guessed, and text on the page cannot change a grade.", "",
        ]
        for c in m["ambiguous_cases"]:
            out.append(f"Ambiguous case: `{c['q']}`: {c['note']}. Pipeline: **{c['pipeline']}**, baseline: {c['baseline']}.")
        out += ["", "### Adversarial pages", "", "| Case | Pass | Detail |", "|---|---|---|"]
        out += [f"| {a['case']} | {'✅' if a['pass'] else '❌'} | {a['detail']} |" for a in g["adversarial"]]
        out.append("")

    hw = load("homework.json")
    if hw:
        out += ["## 2. Personalised homework", "",
                f"Latest homework for the demo class: {hw['children']} children, {hw['items']} questions written by Muse Spark in each child's language.", "",
                "| Check | Result |", "|---|---|",
                f"| Answers re-verified with sympy (and every number in the arithmetic appears in the question) | {hw['items_reverified']} |",
                f"| Identical sheets between any two children | {hw['identical_sheets']} |",
                f"| Mean question overlap between two children | {hw['mean_question_overlap_between_children'] * 100:.1f}% |",
                "| Track mix | " + ", ".join(f"{k}: {v}" for k, v in hw["track_mix"].items()) + " |"]
        out += [f"| {t}: items / mean difficulty level | {v['mean_items']} / {v['mean_level']} |" for t, v in hw["by_track"].items()]
        e = hw.get("end_to_end")
        if e:
            out += ["", f"**End to end:** {e['student']}'s *{e['track']}* sheet was solved in a notebook (photo rendered with two planted mistakes and one "
                    f"question left blank), submitted through her personal link and graded against the answer key: "
                    f"{e['score']['correct']}/{e['score']['total']} correct, {e['score']['total'] - e['score']['attempted']} not attempted. "
                    + "; ".join(f"Q{i['n']} {i['status']}" + (f" ({i['misconception']})" if i["misconception"] else "") for i in e["items"] if i["status"] != "correct") + "."]
        out.append("")

    a = load("agent.json")
    if a:
        out += [
            "## 3. Root-cause agent (Muse Wonder)", "",
            f"{a['agent']['n']} simulated children with a hidden gap concept (`scripts/seed_demo.py`). Neither method sees the hidden gap.", "",
            "| | Exact root | Within 1 prerequisite hop |", "|---|---|---|",
            f"| Muse Wonder agent | {a['agent']['exact']}/{a['agent']['n']} | {a['agent']['within_1_hop']}/{a['agent']['n']} |",
            f"| Knowledge-tracing baseline | {a['baseline_knowledge_tracing']['exact']}/{a['baseline_knowledge_tracing']['n']} | {a['baseline_knowledge_tracing']['within_1_hop']}/{a['baseline_knowledge_tracing']['n']} |",
            "",
            f"Cost ${a['cost_usd']:.2f} total, median {a['median_seconds']} s per child.", "",
            "The baseline above uses the app's teacher-safe rule (a concept needs at least 2 observations before it is called a gap), so it "
            "often abstains. With a lenient single-observation rule the baseline scored 6/10 exact and 8/10 within one hop against the "
            "agent's 5/10 and 7/10 (run log `results/agent_run3.log`).", "",
            "**Honest reading:** the simulator generates evidence the same way knowledge tracing models it, so statistics alone are a strong "
            "baseline; the agent is roughly on par on root identification. Its added value is that it always commits to a reasoned "
            "hypothesis using misconception evidence, explains it to the teacher, names an alternative, and writes sympy-verified probe "
            "questions to test the hypothesis on the child. "
            "Version history: v1 (agent fetched everything through ~20 small tool calls, server-side conversation state) failed on 4/10 "
            "children (expired server state, malformed probe, ran out of turns). v2 puts a compact evidence summary and the knowledge-tracing "
            "estimate in context, uses one subgraph tool, replays state client-side and forces submission on the last turn: 10/10 complete "
            "with 6-7 tool calls each.", "",
        ]

    rd = load("reading.json")
    if rd:
        out += ["## 4. Oral reading assessment (Muse Voice Transcribe)", "",
                "Synthetic Indian voices (macOS Rishi / Lekha / Vani) read each passage cleanly and with planted substitutions and omissions. "
                "Synthetic speech is clearer than a child's, so treat these as upper bounds.", "",
                "| Language | Planted errors caught | False alarms on clean reads |", "|---|---|---|"]
        out += [f"| {lang} | {v['planted_errors_caught']} | {v['false_alarms_on_clean_reads']} |" for lang, v in rd["by_language"].items()]
        fas = [w for r in rd["rows"] for w in r["false_alarm_words"]]
        if fas:
            out += ["", "False alarms were speech-recognition slips, e.g. " + ", ".join(f"`{ref}` heard as `{said}`" for ref, said in fas[:3])
                    + "; the app shows an ASR caveat so the teacher re-listens before acting."]
        out.append("")

    s = load("safety.json")
    if s:
        out += ["## 5. Guardrail red-team", "", f"Child-facing hints caught and repaired: **{s['hints_caught']}** (good hints untouched: {s['good_hints_preserved']}).", "",
                "| Bad hint | Problem | Repaired to |", "|---|---|---|"]
        out += [f"| {h['before']} | {h['case']} | {h['after']} |" for h in s["hints"]]
        out += ["", f"- Budget cap stops API calls: {'✅' if s['budget']['pass'] else '❌'}"]
        out += [f"- Upload rejected ({u['case']}): {'✅' if u['pass'] else '❌'}" for u in s["uploads"]]
        out.append("")

    out += ["## 6. Unit tests", "", "`uv run pytest -q`: deterministic checks of the sympy verifier (Indian digit grouping, decimal commas, remainders, "
            "mixed numbers, comparisons), reading alignment and scoring, hint checks, agent-output validation, concept-graph integrity and "
            "knowledge tracing. No network, no API spend.", ""]
    (HERE / "RESULTS.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
